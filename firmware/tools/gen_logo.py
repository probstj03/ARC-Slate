"""Generates the e-ink logo assets of ARC-Slate from the brand mark in ARC-Server.

    py tools/gen_logo.py [path/to/logo.png]

Input : ../../ARC-Server/server/css/logo.png  (white mark on transparent, made for dark UIs)
Output: src/slate/assets/logo.h        square mark for the "no take selected" panel (drawInvertedBitmap)
        src/slate/assets/bootscreen.h  800x480 boot picture: big mark + "arc slate" title

Bitmaps use the GxEPD2 convention of drawInvertedBitmap: bit 0 = black pixel.
Needs Pillow. The title line "arc slate" is kept from the previous boot picture (brand font);
only the old logo in the top right corner is replaced.
"""
import os
import re
import sys

from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ASSETS = os.path.join(HERE, "..", "src", "slate", "assets")
DEFAULT_LOGO = os.path.join(HERE, "..", "..", "..", "ARC-Server", "server", "css", "logo.png")

MARK_PANEL = 170        # px, mark in the "no take" panel
MARK_BOOT = 120         # px, mark in the boot picture


def mark(path, size):
    """Black disc with the white 'a' cut-out, hard 1-bit edges (alpha threshold after smooth scaling)."""
    im = Image.open(path).convert("RGBA")
    alpha = im.split()[3].resize((size, size), Image.LANCZOS)
    return alpha.point(lambda v: 0 if v >= 128 else 255).convert("1")      # 0 = black


def write_header(path, name, comment, img):
    w, h = img.size
    bw = (w + 7) // 8
    data = bytearray()
    px = img.load()
    for y in range(h):
        for bx in range(bw):
            b = 0
            for k in range(8):
                x = bx * 8 + k
                white = x >= w or px[x, y] != 0
                b = (b << 1) | (1 if white else 0)                  # inverted bitmap: 1 = white, 0 = black
            data.append(b)
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write("#pragma once\n#include <pgmspace.h>\n// %s, %dx%dpx (generated by tools/gen_logo.py)\n" % (comment, w, h))
        f.write("const unsigned char %s [] PROGMEM = {\n" % name)
        for i in range(0, len(data), 16):
            f.write("\t" + ", ".join("0x%02x" % v for v in data[i:i + 16]) + ",\n")
        f.write("};\n")
    print("%s: %dx%d, %d bytes" % (os.path.basename(path), w, h, len(data)))


def read_header(path):
    text = open(path, encoding="utf-8").read()
    m = re.search(r"//[^\n]*?(\d+)x(\d+)px", text)
    w, h = int(m.group(1)), int(m.group(2))
    body = text[text.index("{"):]                        # skip the comment line: "800x480px" contains "0x48"
    data = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{2})", body))
    bw = (w + 7) // 8
    img = Image.new("1", (w, h), 1)
    px = img.load()
    for y in range(h):
        for x in range(w):
            px[x, y] = 1 if (data[y * bw + x // 8] >> (7 - x % 8)) & 1 else 0
    return img


def main():
    src = sys.argv[1] if len(sys.argv) > 1 else DEFAULT_LOGO
    if not os.path.exists(src):
        sys.exit("Logo nicht gefunden: %s" % src)

    boot_path = os.path.join(ASSETS, "bootscreen.h")
    boot_old = os.path.join(ASSETS, "bootscreen_original.png")
    if os.path.exists(boot_old):                       # keep the original title picture as the base
        base = Image.open(boot_old).convert("1")
    else:
        base = read_header(boot_path)
        base.save(boot_old)
        print("Original-Startbild gesichert:", os.path.normpath(boot_old))

    # boot picture: erase the old logo (top right) and put the new mark there
    base = base.copy()
    base.paste(1, (400, 0, 800, 150))
    base.paste(1, (0, 0, 24, 12))                        # stray pixels of the original picture
    m = mark(src, MARK_BOOT)
    base.paste(m, (800 - MARK_BOOT - 24, 24))
    write_header(boot_path, "bootscreen_V2", "Bootscreen_V2", base)

    write_header(os.path.join(ASSETS, "logo.h"), "logo", "logo", mark(src, MARK_PANEL))
    base.save(os.path.join(ASSETS, "bootscreen_preview.png"))


if __name__ == "__main__":
    main()
