"""Night icons of the ARC-Clock matrix, made from the hand drawn icons.

    py -3 tools/night_icons.py src/clock/assets/weather_icons_24x16.h src/clock/assets/weather_icons_night.h

From `clear_night` and `heiter_nacht` (weather_icons_24x16.h) this writes
  * the base frames: `clear_night` empty, `heiter_nacht` with the clouds of all frames, the top half (moon + stars) cleared,
  * the moon position (column of the 8x8 moon, centred on the drawn moon) and the star positions.
The firmware draws the moon with the real phase and the stars on top (ac::composeNightIcon, core/anim.cpp).
"""
import re
import sys


def frames(txt, name):
    res = []
    for m in re.finditer(r"icon16_%s_f(\d+)\[48\] = \{([^}]*)\}" % name, txt):
        b = [int(x, 16) for x in re.findall(r"0x[0-9A-Fa-f]{2}", m.group(2))]
        res.append([[(b[y * 3 + x // 8] >> (7 - x % 8)) & 1 for x in range(24)] for y in range(16)])
    return res


def components(img):
    """Connected pixels (4-neighbourhood); the gap between row 7 and 8 separates the halves."""
    seen, comps = set(), []
    for y in range(16):
        for x in range(24):
            if img[y][x] and (x, y) not in seen:
                stack, comp = [(x, y)], []
                seen.add((x, y))
                while stack:
                    cx, cy = stack.pop()
                    comp.append((cx, cy))
                    for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                        nx, ny = cx + dx, cy + dy
                        if 0 <= nx < 24 and 0 <= ny < 16 and img[ny][nx] and (nx, ny) not in seen and (cy < 8) == (ny < 8):
                            seen.add((nx, ny))
                            stack.append((nx, ny))
                comps.append(comp)
    return comps


def analyse(txt, name, stars_in_bottom_half):
    fr = frames(txt, name)
    top = [c for c in components(fr[0]) if all(y < 8 for _, y in c)]
    moon = max(top, key=len)                                 # the largest shape of the top half
    xs = [x for x, _ in moon]
    moon_x = max(0, min(16, round((min(xs) + max(xs)) / 2 - 3.5)))
    stars = []
    for f in fr[:3]:                                         # stars of the first frames, merged
        for c in components(f):
            if len(c) > 6:
                continue
            if not stars_in_bottom_half and any(y >= 8 for _, y in c):
                continue
            cx = round(sum(x for x, _ in c) / len(c))
            cy = round(sum(y for _, y in c) / len(c))
            if cy <= 8 and moon_x - 2 <= cx <= moon_x + 9:   # not on the moon
                continue
            if any(max(abs(cx - sx), abs(cy - sy)) < 3 for sx, sy in stars):
                continue
            stars.append((cx, cy))
    return fr, moon_x, stars[:8]


def emit_frame(f, name, img):
    f.write("const uint8_t PROGMEM %s[48] = {\n" % name)
    for y in range(16):
        bs = [sum(img[y][bx * 8 + k] << (7 - k) for k in range(8)) for bx in range(3)]
        f.write("  " + ", ".join("0x%02X" % b for b in bs) + (",\n" if y < 15 else "\n"))
    f.write("};\n\n")


def main():
    src, out = sys.argv[1], sys.argv[2]
    txt = open(src, encoding="utf-8").read()
    with open(out, "w", encoding="ascii", newline="\n") as f:
        f.write("// Night icons without moon and stars: the clouds of heiter_nacht, an empty frame for clear_night, plus the\n")
        f.write("// moon column and the star positions of the hand drawn icons. Generated by tools/night_icons.py - do not edit.\n")
        f.write("// The firmware adds the moon of the real phase and the stars (ac::composeNightIcon).\n")
        f.write("#pragma once\n#include <stdint.h>\n#ifndef PROGMEM\n#define PROGMEM\n#endif\n\n")
        for key, name, bottom in (("clear", "clear_night", True), ("heiter", "heiter_nacht", False)):
            fr, moon_x, stars = analyse(txt, name, bottom)
            base = [[[0] * 24 for _ in range(16)]] if key == "clear" else \
                   [[row[:] if y >= 8 else [0] * 24 for y, row in enumerate(img)] for img in fr]
            upper = key.upper()
            f.write("constexpr int NIGHT_%s_MOON_X = %d;\n" % (upper, moon_x))
            f.write("constexpr int NIGHT_%s_STAR_N = %d;\n" % (upper, len(stars)))
            f.write("const int8_t night_%s_stars[NIGHT_%s_STAR_N][2] = { %s };\n\n" %
                    (key, upper, ", ".join("{%d, %d}" % s for s in stars)))
            for i, img in enumerate(base):
                emit_frame(f, "icon16_%s_base_f%d" % (name, i), img)
            f.write("#define ANIM16_%s_BASE_LEN %d\n" % (name.upper(), len(base)))
            f.write("const uint8_t* const anim16_%s_base[ANIM16_%s_BASE_LEN] = { %s };\n\n" %
                    (name, name.upper(), ", ".join("icon16_%s_base_f%d" % (name, i) for i in range(len(base)))))
            print(name, "moon x", moon_x, "stars", stars, "frames", len(base))


main()
