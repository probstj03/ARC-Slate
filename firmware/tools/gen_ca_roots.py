"""Generates src/clock/ca_roots.h: a curated set of common root certificates (Mozilla list via curl.se)
for HTTPS requests to Nextcloud and Open-Meteo.

    py tools/gen_ca_roots.py [path/to/cacert.pem]      (downloads https://curl.se/ca/cacert.pem otherwise)

Own CA (self-hosted Nextcloud): put its PEM into /ca.pem on the device (LittleFS) or use `nc cert`.
"""
import os
import re
import sys
import urllib.request

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, "..", "src", "clock", "ca_roots.h")
URL = "https://curl.se/ca/cacert.pem"

WANTED = [
    "ISRG Root X1", "ISRG Root X2",
    "DigiCert Global Root G2", "DigiCert Global Root G3", "DigiCert Global Root CA",
    "DigiCert TLS RSA4096 Root G5", "DigiCert TLS ECC P384 Root G5",
    "GlobalSign Root CA - R3", "GlobalSign Root R46", "GlobalSign ECC Root CA - R5",
    "Amazon Root CA 1", "Amazon Root CA 2", "Amazon Root CA 3", "Amazon Root CA 4",
    "Baltimore CyberTrust Root",
    "USERTrust RSA Certification Authority", "USERTrust ECC Certification Authority",
    "COMODO RSA Certification Authority", "Sectigo Public Server Authentication Root R46",
    "Starfield Services Root Certificate Authority - G2",
    "GTS Root R1", "GTS Root R2", "GTS Root R3", "GTS Root R4",
    "D-TRUST Root Class 3 CA 2 2009", "D-TRUST BR Root CA 1 2020", "D-TRUST EV Root CA 1 2020",
    "Telekom Security TLS RSA Root 2023", "Telekom Security TLS ECC Root 2020",
    "T-TeleSec GlobalRoot Class 2", "T-TeleSec GlobalRoot Class 3",
    "SwissSign Gold CA - G2",
    "Microsoft RSA Root Certificate Authority 2017", "Microsoft ECC Root Certificate Authority 2017",
    "Cloudflare Inc ECC CA-3",
]


def main():
    if len(sys.argv) > 1:
        text = open(sys.argv[1], encoding="utf-8").read()
    else:
        print("Lade", URL)
        text = urllib.request.urlopen(URL, timeout=60).read().decode("utf-8")
    blocks = re.findall(r"^([^\n#=][^\n]*)\n=+\n(?:[^\n]*\n)*?(-----BEGIN CERTIFICATE-----.*?-----END CERTIFICATE-----)",
                        text, re.S | re.M)
    by_name = {name.strip(): pem for name, pem in blocks}
    chosen, missing = [], []
    for name in WANTED:
        (chosen if name in by_name else missing).append(name)
    if not chosen:
        sys.exit("Keine Zertifikate gefunden - Format von cacert.pem geaendert?")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/gen_ca_roots.py from the Mozilla root list (curl.se). Do not edit.\n")
        f.write("#pragma once\n// %d root certificates for HTTPS (Nextcloud, Open-Meteo).\n" % len(chosen))
        f.write("static const char kCaRoots[] =\n")
        for name in chosen:
            f.write("    // %s\n" % name)
            for line in by_name[name].splitlines():
                f.write('    "%s\\n"\n' % line.strip())
        f.write("    ;\n")
    print("%d Zertifikate -> %s" % (len(chosen), os.path.normpath(OUT)))
    if missing:
        print("Nicht im Bundle gefunden:", ", ".join(missing))


if __name__ == "__main__":
    main()
